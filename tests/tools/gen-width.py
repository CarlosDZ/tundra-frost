#!/usr/bin/env python3
import sys
import unicodedata

VERSION = "16.0.0"
if unicodedata.unidata_version != VERSION:
    sys.exit(f"gen-width: Python has Unicode {unicodedata.unidata_version}, "
             f"not {VERSION}")

def width(cp):
    if cp == 0x00AD:
        return 1
    c = chr(cp)
    cat = unicodedata.category(c)
    if cat in ("Mn", "Me", "Cf") or cp == 0x200B:
        return 0
    if 0x1160 <= cp <= 0x11FF or 0xD7B0 <= cp <= 0xD7FF:
        return 0
    if unicodedata.east_asian_width(c) in ("W", "F"):
        return 2
    return 1

def ranges(w):
    out, start = [], None
    for cp in range(0x300, 0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            hit = False
        else:
            hit = width(cp) == w
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out

def table(name, rs):
    print(f"static const struct width_range {name}[] = {{")
    for a, b in rs:
        print(f"\t{{0x{a:05X}, 0x{b:05X}}},")
    print("};")

print(f"/* Generated by tests/tools/gen-width.py from Unicode {VERSION} */")
print()
print("/* clang-format off */")
table("width_zero", ranges(0))
print()
table("width_wide", ranges(2))
print("/* clang-format on */")
